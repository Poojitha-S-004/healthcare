const dictionaries = { en, hi } as const;
export type TranslationKey = keyof typeof en;

export function translate(language: AppLanguage, key: TranslationKey) {
  return dictionaries[language][key];
}

export function priorityLabel(language: AppLanguage, priority: Priority) {
  return translate(language, priority);
}

export function priorityReasonLabel(language: AppLanguage, reason: PriorityReason) {
  return translate(language, reason);
}

export function syncLabel(language: AppLanguage, state: SyncState) {
  return translate(language, state);
}

export function referralLabel(language: AppLanguage, status: ReferralStatus) {
  const labels: Record<ReferralStatus, string> = {
    draft: language === "hi" ? "मसौदा" : "Draft",
    sent: language === "hi" ? "भेजा गया" : "Sent",
    accepted: language === "hi" ? "स्वीकार" : "Accepted",
    awaitingTransport: language === "hi" ? "परिवहन की प्रतीक्षा" : "Awaiting transport",
    inTransit: language === "hi" ? "रास्ते में" : "In transit",
    arrived: language === "hi" ? "पहुंच गया" : "Arrived",
    completed: language === "hi" ? "पूर्ण" : "Completed",
    followUpOverdue: language === "hi" ? "अनुवर्ती लंबित" : "Follow-up overdue",
  };
  return labels[status];
}
